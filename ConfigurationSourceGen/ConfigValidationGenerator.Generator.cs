using System.Collections.Generic;
using System.Linq;

namespace ConfigurationSourceGen;

public partial class ConfigValidationGenerator {
    private static string GenerateRawClass(ToGenerateClass cls) {
        CodeBuilder builder = new();
        builder.AddLine("// <auto-generated/>");
        builder.AddNamespace(cls.Namespace);
        GenerateAttributes(builder, cls.Attributes);
        builder.AddClass($"Raw{cls.Name}");

        foreach (ToGenerateProperty prop in cls.Properties) {
            string resolvedType = ResolveType(prop.Type);
            GenerateAttributes(builder, prop.Attributes);
            builder.AddProperty(resolvedType, prop.Name, new PropertyOptions {
                Visibility = Visibility.Public,
                HasGet = true,
                HasSet = true
            });
        }

        // Méthode ToXxx() → renvoie (Xxx result, List<string> errors)
        builder.AddMethod(
            $"To{cls.Name}",
            new MethodOptions { ReturnType = $"({cls.Name} result, List<string> errors)", Parameters = [("string?", "path = null")] }
        );

        builder.AddLine($"{cls.Name} result = new();");
        builder.AddLine("List<string> errors = new();");
        builder.AddLine($"path ??= nameof({cls.Name});");

        foreach (ToGenerateProperty prop in cls.Properties)
            GenerateAssignment(builder, prop);

        builder.AddLine("return (result, errors);");
        builder.EndBlock(); // method
        builder.EndBlock(); // class
        builder.EndBlock(); // namespace

        return builder.Build();
    }

    private static string ResolveType(TypeDefinition type) {
        if (type.IsRaw)
            return $"{type.Namespace}.Raw{type.Name}";

        if (type.Generics.Count > 0) {
            string generics = string.Join(", ", type.Generics.Select(ResolveType));
            return $"{type.Namespace}.{type.Name}<{generics}>";
        }

        return "string";
    }

    private static void GenerateAssignment(CodeBuilder builder, ToGenerateProperty prop) {
        string name = prop.Name;
        TypeDefinition type = prop.Type;
        builder.If($"{name} != null", () => {
            if (type.IsRaw) {
                builder.AddLine($"var (converted{name}, subErrors{name}) = {name}.To{type.Name}($\"{{path}}.{name}\");");
                builder.AddLine($"result.{name} = converted{name};");
                builder.AddLine($"errors.AddRange(subErrors{name});");
            } else if (type.Name == "String") {
                builder.AddLine($"result.{name} = {name};");
            } else if (type.IsEnum) {
                builder.If($"Enum.TryParse<{type.Namespace}.{type.Name}>({name}, true, out var parsed{name})", () => {
                    builder.AddLine($"result.{name} = parsed{name};");
                });
                builder.Else(() => {
                    builder.AddLine($"errors.Add($\"{{path}}.{name} must be a valid {type.Name} enum value.\");");
                });
            } else if (type.Name == "List" && type.Generics.Count == 1) {
                builder.AddLine($"int index = 0;");
                builder.Foreach($"var item in {name}", () => {
                    if (!type.Generics[0].IsRaw)
                        builder.AddLine($"result.{name}.Add(item);");
                    else {
                        builder.AddLine($"var (convertedItem, subErrors) = item.To{type.Generics[0].Name}($\"{{path}}.{name}[{{index}}]\");");
                        builder.AddLine($"result.{name}.Add(convertedItem);");
                        builder.AddLine($"errors.AddRange(subErrors);");
                    }
                    builder.AddLine("index++;");
                });
            } else {
                GenerateTryParse(builder, name, type.Name);
            }
        });

        if (!type.IsNullable) {
            builder.Else(() => {
                builder.AddLine($"errors.Add($\"{{path}}.{name} cannot be null.\");");
            });
        }
    }

    private static void GenerateTryParse(CodeBuilder builder, string name, string type) {
        builder.If($"{type}.TryParse({name}, out {type} parsed{name})", () => {
            builder.AddLine($"result.{name} = parsed{name};");
        });
        builder.Else(() => {
            builder.AddLine($"errors.Add($\"{{path}}.{name} must be a valid {type}.\");");
        });
    }

    private static void GenerateAttributes(CodeBuilder builder, List<AttributeDefinition> attributes) {
        foreach (AttributeDefinition attr in attributes) {
            string fullName = $"{attr.Namespace}.{attr.Name}".Replace("::.", "::");
            string args = attr.Arguments.Count > 0
                ? $"({string.Join(", ", attr.Arguments)})"
                : "";
            builder.AddLine($"[{fullName}{args}]");
        }
    }

}
